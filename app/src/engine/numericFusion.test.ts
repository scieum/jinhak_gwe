import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it, vi } from 'vitest';
import { compareHistoricalPrograms, createNumericFusion, type HistoricalProgram, type NumericFusionBundle } from './numericFusion';

const folder = resolve(process.cwd(), '../work/_research/five-to-nine-2026-11-26/numeric-runtime');
const bundle = JSON.parse(readFileSync(resolve(folder, 'model.json'), 'utf8')) as NumericFusionBundle;
const gold = JSON.parse(readFileSync(resolve(folder, 'python-parity.json'), 'utf8')) as {
  grade_ranges: { grade: number; range: [number, number] | null }[];
  full_cases: { grade5: number; population_scenarios: { population_n: number; regional_cases: {
    estimated_all_one_n: number; estimated_through_grade_n: number | null;
    cases: { all_one_medical_intent_n: number; all_one_effective_demand_n: number;
      segment_to_provisional_collected_seats: number | null;
      other_candidates_needed_to_match_collected_seats: number; segment_excess_over_collected_seats: number }[] }[] }[] }[];
};
const engine = () => createNumericFusion(bundle, { mode: 'research' });

describe('numeric fusion runtime', () => {
  it('matches Python at every 0.001 grade across the full input domain', () => {
    const model = engine();
    for (const c of gold.grade_ranges) {
      const actual = model.calculate(c.grade).grade9Range;
      if (c.range === null) expect(actual).toBeNull();
      else {
        expect(actual?.[0], `lower at ${c.grade}`).toBeCloseTo(c.range[0], 10);
        expect(actual?.[1], `upper at ${c.grade}`).toBeCloseTo(c.range[1], 10);
      }
    }
  });

  it('matches cohort and medical scenario calculations independently generated by Python', () => {
    const model = engine();
    for (const full of gold.full_cases) {
      const result = model.calculate(full.grade5);
      full.population_scenarios.forEach((p, i) => {
        expect(result.populationScenarios[i].populationN).toBe(p.population_n);
        p.regional_cases.forEach((r, j) => {
          const actual = result.populationScenarios[i].regionalCases[j];
          expect(actual.estimatedAllOneN).toBeCloseTo(r.estimated_all_one_n, 8);
          if (r.estimated_through_grade_n === null) expect(actual.estimatedThroughGradeN).toBeNull();
          else expect(actual.estimatedThroughGradeN).toBeCloseTo(r.estimated_through_grade_n, 8);
          r.cases.forEach((c, k) => {
            const a = actual.cases[k];
            expect(a.allOneMedicalIntentN).toBeCloseTo(c.all_one_medical_intent_n, 8);
            expect(a.allOneEffectiveDemandN).toBeCloseTo(c.all_one_effective_demand_n, 8);
            if (c.segment_to_provisional_collected_seats === null) expect(a.segmentToProvisionalSeats).toBeNull();
            else expect(a.segmentToProvisionalSeats).toBeCloseTo(c.segment_to_provisional_collected_seats, 10);
            expect(a.additionalCandidatesToMatchSeats).toBeCloseTo(c.other_candidates_needed_to_match_collected_seats, 8);
            expect(a.segmentExcessOverSeats).toBeCloseTo(c.segment_excess_over_collected_seats, 8);
          });
        });
      });
    }
  });

  it('runs synchronously with network unavailable and produces the same result repeatedly', () => {
    const fetcher = vi.fn(() => { throw new Error('Offline'); });
    vi.stubGlobal('fetch', fetcher);
    try {
      const model = engine();
      const expected = model.calculate('1.3');
      expect(expected).not.toBeInstanceOf(Promise);
      for (let i = 0; i < 20; i++) expect(model.calculate(1.3)).toEqual(expected);
      expect(fetcher).not.toHaveBeenCalled();
    } finally { vi.unstubAllGlobals(); }
  });

  it('takes an isolated snapshot and does not expose mutable internal coefficients', () => {
    const data = structuredClone(bundle), model = createNumericFusion(data, { mode: 'research' });
    const before = model.calculate(1.3);
    data.capacity.provisionalSeats = 1; data.curves[0].y5.fill(5);
    const returned = model.calculate(1.3); returned.capacity.provisionalSeats = 2;
    returned.populationScenarios[0].regionalCases[0].cases[0].allOneEffectiveDemandN = 0;
    expect(model.calculate(1.3)).toEqual(before);
  });

  it('does not enable an unreviewed bundle in production by default', () => {
    expect(() => createNumericFusion(bundle)).toThrow('research-only');
    expect(() => createNumericFusion(bundle, { mode: 'production' })).toThrow('research-only');
  });

  it('rejects blank, nonnumeric and out of range user input', () => {
    const model = engine();
    for (const g of ['', ' ', 'abc', '1,3', '1.3등급', '0x2', '1e0', NaN, Infinity, 0.9, 5.1]) {
      expect(() => model.calculate(g)).toThrow();
    }
    expect(model.calculate(' 1.30 ')).toEqual(model.calculate(1.3));
  });

  it('rejects malformed coefficient data', () => {
    const changed: NumericFusionBundle[] = [];
    let b = structuredClone(bundle); b.curves[0].x9[1] = b.curves[0].x9[0]; changed.push(b);
    b = structuredClone(bundle); b.references[0].points[1][1] = -1; changed.push(b);
    b = structuredClone(bundle); b.capacity.provisionalSeats = NaN; changed.push(b);
    b = structuredClone(bundle); b.intentRates = [1.2]; changed.push(b);
    b = structuredClone(bundle); b.populations.push(b.populations[0]); changed.push(b);
    for (const value of [null, {}, ...changed]) expect(() => createNumericFusion(value, { mode: 'research' })).toThrow();
  });

  it('preserves the 1.00 plateau and does not extrapolate unsupported curves', () => {
    const b = structuredClone(bundle);
    b.curves = [{ x9: [1, 2, 3], y5: [1, 1, 2] }, { x9: [1, 2, 3], y5: [1, 1, 2] }];
    b.references = [{ points: [[1, .01, 1], [2, .2, 3]] }];
    const model = createNumericFusion(b, { mode: 'research' });
    expect(model.calculate(1).grade9Range?.[1]).toBeCloseTo(2.005, 10);
    expect(model.calculate(5).grade9Range).toBeNull();
  });

  it('changes demand ratio, not grade equivalence, when capacity changes', () => {
    const b = structuredClone(bundle); b.capacity.provisionalSeats *= 2;
    const a = engine().calculate(1.3), doubled = createNumericFusion(b, { mode: 'research' }).calculate(1.3);
    expect(doubled.grade9Range).toEqual(a.grade9Range);
    const ratio = (r: typeof a) => r.populationScenarios[0].regionalCases[0].cases[0].segmentToProvisionalSeats!;
    expect(ratio(doubled)).toBeCloseTo(ratio(a) / 2, 10);
  });

  it('returns no invented university line or admission probability', () => {
    const r = engine().calculate(1.3);
    expect(r.universityLine).toBeNull(); expect(r.admissionProbability).toBeNull();
    expect(r.assumptionsApplied).toBe(true); expect(r.gradeDefinitionMatched).toBe(false);
    for (const name of ['gyeonggi', 'busan', 'youniv', 'source_file']) expect(JSON.stringify(r)).not.toContain(name);
  });
});

describe('deterministic historical program comparison', () => {
  const row: HistoricalProgram = { id: 'a', university: '가상대', department: '가상학과', year: 2026,
    track: '교과', gradeSystem: 9, statistic: 'cut70', grade: 1.9, basisId: 'core-credits', reviewStatus: 'verified' };
  const filter = { year: 2026, track: '교과', statistic: 'cut70' as const, basisId: 'core-credits' };
  it('filters year, track, statistic, basis and review status before comparison', () => {
    const rows: HistoricalProgram[] = [row, { ...row, id: 'b', reviewStatus: 'draft' },
      { ...row, id: 'c', statistic: 'cut50' }, { ...row, id: 'd', year: 2025 },
      { ...row, id: 'e', track: '종합' }, { ...row, id: 'f', basisId: 'all-simple' }];
    const result = compareHistoricalPrograms(engine().calculate(1.3), rows, filter);
    expect(result).toHaveLength(1);
    expect(result[0]).toMatchObject({ id: 'a', relation: 'overlaps_reference', distance: 0 });
  });
  it('compares numeric distances without equating a cutoff to admission probability', () => {
    const result = compareHistoricalPrograms(engine().calculate(1.3), [
      row, { ...row, id: 'b', grade: 1.5 }, { ...row, id: 'c', grade: 2.5 }], filter);
    expect(result.map(r => r.relation)).toEqual(['overlaps_reference', 'historical_grade_stronger', 'historical_grade_weaker']);
    expect(result[1].distance).toBeCloseTo(.235, 10);
    expect(result[2].distance).toBeCloseTo(.415, 10);
  });
  it('rejects duplicate records and refuses to substitute an average for a missing cutoff', () => {
    expect(() => compareHistoricalPrograms(engine().calculate(1.3), [row, row], filter)).toThrow();
    expect(compareHistoricalPrograms(engine().calculate(1.3), [{ ...row, grade: 1.9, statistic: 'cut50' }], filter)).toEqual([]);
  });
});
