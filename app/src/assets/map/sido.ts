const path = (ring: LngLat[]) => ring.map((p, i) => `${i ? 'L' : 'M'}${project(p).map(n => n.toFixed(1)).join(' ')}`).join('') + 'Z';
export interface SidoShape { d: string; label: [number, number]; marker: [number, number]; bbox: { x: number; y: number; w: number; h: number } }
export const SIDO_SHAPES = Object.fromEntries(SIDO.map(s => {
  const pts = RINGS[s][0].map(project), xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  const x = Math.min(...xs), y = Math.min(...ys);
  return [s, { d: RINGS[s].map(path).join(''), label: project(LABEL[s]), marker: project(CALLOUT[s] ?? LABEL[s]), bbox: { x, y, w: Math.max(...xs) - x, h: Math.max(...ys) - y } }];
})) as Record<Sido, SidoShape>;
