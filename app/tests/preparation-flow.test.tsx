import 'fake-indexeddb/auto';
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, beforeEach, expect, test, vi } from 'vitest';
import { App } from '../src/App';
import { studentDb } from '../src/store/studentDb';
import { newApplication, newCounselTask } from '../src/domain/planner';
beforeEach(async () => { await studentDb.clearStudentData(); });
afterEach(cleanup);
const at = (path: string) => render(<MemoryRouter initialEntries={[path]}><App /></MemoryRouter>);
const seed = async () => { const p = { ...newApplication(), university: '흐름 테스트 대학', program: '교과 가상 전형' }; await studentDb.saveApplication(p); return p; };
test('전형 추가 → 독립 체크 단계 완료 → 화면 재진입 후 기록 유지', async () => {
  const fetchSpy = vi.spyOn(globalThis, 'fetch');
  const first = at('/application-checklist');
  await screen.findByText('준비할 전형을 먼저 추가해 주세요');
  fireEvent.click(screen.getByRole('button', { name: '+ 지원 전형 추가' }));
  const dialog = screen.getByRole('dialog', { name: '지원 전형 편집' });
  fireEvent.change(within(dialog).getByLabelText('대학명'), { target: { value: '흐름 테스트 대학' } });
  fireEvent.change(within(dialog).getByLabelText('전형명'), { target: { value: '교과 가상 전형' } });
  fireEvent.click(within(dialog).getByRole('button', { name: '저장' }));
  fireEvent.click(await screen.findByRole('button', { name: '원서 작성 수정' }));
  fireEvent.change(screen.getByLabelText('진행 상태'), { target: { value: 'done' } });
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '저장' }));
  await waitFor(async () => expect((await studentDb.applications.toArray())[0].steps[0].status).toBe('done'));
  expect((await studentDb.applications.toArray())[0].steps[1].status).toBe('pending');
  first.unmount(); at('/application-checklist');
  expect(await screen.findByRole('heading', { name: '흐름 테스트 대학 · 교과 가상 전형' })).toBeTruthy();
  expect(await screen.findByText('처리 완료')).toBeTruthy();
  expect(fetchSpy).not.toHaveBeenCalled(); fetchSpy.mockRestore();
});
test('자격 조건은 초기 미확인 → 근거와 미충족 기록, 확인 기록 일시 보존', async () => {
  const p = await seed(); at(`/eligibility-check?plan=${p.id}`);
  fireEvent.click(await screen.findByRole('button', { name: '지역·학교 조건 수정' }));
  fireEvent.change(screen.getByLabelText('내 확인 상태'), { target: { value: 'unmet' } });
  fireEvent.change(screen.getByLabelText('조건·확인 근거·문의할 담당자'), { target: { value: '모집요강 5쪽, 담당자에게 재확인할 내용' } });
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '저장' }));
  expect(await screen.findByText('미충족 기록 있음')).toBeTruthy();
  const saved = (await studentDb.applications.get(p.id))!;
  expect(saved.eligibility[2].checked_at).not.toBeNull(); expect(saved.eligibility[0].status).toBe('unknown');
});
test('상담 전 질문 저장 → 완료 → 완료 필터 → 다시 진행', async () => {
  await seed(); at('/counsel-tasks');
  await screen.findByText('표시할 상담 항목이 없어요');
  fireEvent.click(screen.getByRole('button', { name: '+ 질문·할 일 추가' }));
  fireEvent.change(screen.getByLabelText('구분'), { target: { value: 'question' } });
  fireEvent.change(screen.getByLabelText('제목'), { target: { value: '추천 조건 질문하기' } });
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '저장' }));
  fireEvent.click(await screen.findByRole('button', { name: '완료로 표시' }));
  await waitFor(async () => expect((await studentDb.tasks.toArray())[0].done).toBe(true));
  fireEvent.change(screen.getByLabelText('완료 상태'), { target: { value: 'done' } });
  fireEvent.click(await screen.findByRole('button', { name: '다시 진행' }));
  await waitFor(async () => expect((await studentDb.tasks.toArray())[0].completed_at).toBeNull());
});
test('전형 삭제는 확인 뒤 실행하고 연결된 상담은 유지', async () => {
  const p = await seed(); await studentDb.saveTask({ ...newCounselTask(p.id), title: '남길 상담 메모' });
  at('/application-checklist');
  fireEvent.click(await screen.findByRole('button', { name: '전형 삭제' }));
  expect(await studentDb.applications.count()).toBe(1);
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '삭제' }));
  await waitFor(async () => expect(await studentDb.applications.count()).toBe(0));
  expect((await studentDb.tasks.toArray())[0]).toMatchObject({ title: '남길 상담 메모', application_id: null });
});
